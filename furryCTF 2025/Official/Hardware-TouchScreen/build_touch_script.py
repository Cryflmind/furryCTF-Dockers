# 插入陷阱: 每隔 7 个正常坐标，随机加一个 noncontig
enhanced_events = []
for i, ev in enumerate(events):
    enhanced_events.append(ev)
    if i % 7 == 0:
        enhanced_events.append({"type": "noncontig", "t": random.randint(1,3)})

config = {
    "frame": {"x": 100, "y": 100},
    "mode": "tracking",
    "add_exit": False,
    "touch_scanning_on": False,    # 必须玩家手动开
    "report_transfer_on": False,   # 必须玩家手动开
    "streaming_mode": True,        # 一旦开传输，持续推送
    "echo": False,
    "loop": True,                  # 无限循环，让玩家能多次试
    "stream_delay_ms": 30,
    "events": enhanced_events
}

with open("touches.ctf.json", "w") as f:
    json.dump(config, f, indent=2)


events = []

x_cursor = start_x
# 单数据模式
for ch in flag:
    grid = font5x7.get(ch, [])
    for y, row in enumerate(grid):
        for x, pixel in enumerate(row):
            if pixel == "#":
                events.append({"type": "touch", "x": x_cursor + x, "y": start_y + y})
    x_cursor += 5 + spacing

